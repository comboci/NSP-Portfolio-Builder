const blocks=[...source.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script\s*>/gi)].filter(m=>!/\btype=["'](?:application\/json|application\/ld\+json|module)/i.test(m[1])&&!/\bsrc=/.test(m[1]));
